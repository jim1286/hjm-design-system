/* eslint-disable @typescript-eslint/no-require-imports -- Expo loads local config plugins synchronously through CommonJS during prebuild. */
const {
  withInfoPlist,
  withAppDelegate,
  withXcodeProject,
  withDangerousMod,
} = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

/**
 * iOS 27 requires the scene lifecycle, but Expo 57.0.24's prebuild template does not
 * connect its ExpoAppSceneDelegate. Generating the bridge here survives clean EAS
 * prebuilds; editing generated ios/ files would not (docs/LIBRARY_POLICY.md, iOS 27 launch fix).
 * Remove this plugin when Expo's template adopts scenes, after checking the scene
 * manifest and delegate are not generated twice. The HJM iOS 27 crash report confirms the no-scene-lifecycle UIKit trap.
 */
const DELEGATE_FILE = 'SceneDelegate.swift';
const DELEGATE_CLASS = '$(PRODUCT_MODULE_NAME).SceneDelegate';
const WINDOW_MARKER = '// UIWindow is created by SceneDelegate after the scene connects.';
const START_MARKER = '// SceneDelegate starts React Native in its scene-owned window.';
const DELEGATE_SOURCE = `// Generated by plugins/with-ios-scene-lifecycle.cjs. Do not edit.
// Expo forwards scene URLs, user activities and lifecycle events to AppDelegate,
// preserving cold-start links and the subscribers used by existing Expo modules.
internal import Expo

class SceneDelegate: ExpoAppSceneDelegate {}
`;

function patchAppDelegate(contents) {
  const delegateClass = 'class AppDelegate: ExpoAppDelegate';
  const providerClass = `${delegateClass}, ExpoReactNativeFactoryProvider`;
  const window = /^[ \t]*window = UIWindow\(frame: UIScreen\.main\.bounds\)\r?\n/m;
  const start =
    /^[ \t]*factory\.startReactNative\(\s*withModuleName: "main",\s*in: window,\s*launchOptions: launchOptions\s*\)\r?\n/m;

  if (
    contents.includes(providerClass) &&
    contents.includes(WINDOW_MARKER) &&
    contents.includes(START_MARKER) &&
    !window.test(contents) &&
    !start.test(contents)
  ) {
    return contents;
  }
  // Fail closed on template changes: a successful prebuild with no effective scene
  // wiring still produces an app that crashes on iOS 27. Review upstream adoption.
  if (!contents.includes(`${delegateClass} {`) || !window.test(contents) || !start.test(contents)) {
    throw new Error(
      'with-ios-scene-lifecycle: unsupported AppDelegate template; review Expo scene adoption before releasing.',
    );
  }
  // Patch these statements separately so another plugin's initialization between
  // them (for example a native SDK configure call) remains in didFinishLaunching.
  return contents
    .replace(`${delegateClass} {`, `${providerClass} {`)
    .replace(window, `    ${WINDOW_MARKER}\n`)
    .replace(start, `    ${START_MARKER}\n`);
}

function withSceneLifecycle(config) {
  const version = require('expo/package.json').version;
  const [major, minor, patch] = version.split('.').map(Number);
  if (major !== 57 || minor !== 0 || patch < 24) {
    throw new Error(
      `with-ios-scene-lifecycle requires Expo 57.0.24 or newer in SDK 57; found ${version}. Review native compatibility before releasing.`,
    );
  }
  config = withInfoPlist(config, (mod) => {
    const manifest = mod.modResults.UIApplicationSceneManifest ?? {};
    const configurations = manifest.UISceneConfigurations ?? {};
    const existing = configurations.UIWindowSceneSessionRoleApplication;
    if (
      existing &&
      (existing.length !== 1 || existing[0].UISceneDelegateClassName !== DELEGATE_CLASS)
    ) {
      throw new Error(
        'with-ios-scene-lifecycle: scene configuration already exists; review upstream adoption instead of overwriting it.',
      );
    }
    mod.modResults.UIApplicationSceneManifest = {
      ...manifest,
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        ...configurations,
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: DELEGATE_CLASS,
          },
        ],
      },
    };
    return mod;
  });
  config = withAppDelegate(config, (mod) => {
    if (mod.modResults.language !== 'swift') {
      throw new Error('with-ios-scene-lifecycle requires the Expo Swift AppDelegate template.');
    }
    mod.modResults.contents = patchAppDelegate(mod.modResults.contents);
    return mod;
  });
  config = withDangerousMod(config, [
    'ios',
    (mod) => {
      const directory = path.join(mod.modRequest.platformProjectRoot, mod.modRequest.projectName);
      fs.writeFileSync(path.join(directory, DELEGATE_FILE), DELEGATE_SOURCE, 'utf8');
      return mod;
    },
  ]);
  config = withXcodeProject(config, (mod) => {
    const project = mod.modResults;
    const group = mod.modRequest.projectName;
    const file = `${group}/${DELEGATE_FILE}`;
    if (!project.hasFile(file)) {
      project.addSourceFile(
        file,
        { target: project.getFirstTarget().uuid },
        project.findPBXGroupKey({ name: group }),
      );
    }
    return mod;
  });
  return config;
}

module.exports = withSceneLifecycle;
module.exports.patchAppDelegate = patchAppDelegate;
