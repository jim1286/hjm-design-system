import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { ActivityIndicator, Pressable, View } from "react-native";
import { afterEach, expect, it, vi } from "vitest";
import { Button } from "../src/actions.js";
import { Text } from "../src/primitives.js";
import { HjmNativeProvider } from "../src/provider.js";
(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
let tree: ReactTestRenderer;
afterEach(() => act(() => tree?.unmount()));
it.each(["Saved", "Your changes have been saved successfully"])("reserves both native text labels across pending and confirmed states: %s", label => {
  const press = vi.fn();
  const render = (loading: boolean, confirmed: boolean) => <HjmNativeProvider><Button loading={loading} completion={{ confirmed, label }} onPress={press}>Save</Button></HjmNativeProvider>;
  act(() => { tree = create(render(false, false)); });
  const slot = () => tree.root.findAllByType(View).find(node => node.props.style?.flexShrink === 1 && typeof node.props.style?.height === "number")!;
  const initial = slot().props.style;
  const labels = () => tree.root.findAllByType(Text).filter(node => node.props.onLayout);
  expect(labels().map(node => node.props.children)).toEqual(["Save", label]);
  act(() => { labels()[0]!.props.onLayout({ nativeEvent: { layout: { height: 20, width: 40 } } }); labels()[1]!.props.onLayout({ nativeEvent: { layout: { height: 40, width: 180 } } }); });
  expect(slot().props.style).toEqual(initial);
  act(() => tree.update(render(true, true)));
  expect(slot().props.style).toEqual(initial);
  expect(tree.root.findByType(Pressable).props.accessibilityLabel).toBe("Save");
  expect(tree.root.findByType(ActivityIndicator)).toBeTruthy();
  act(() => tree.root.findByType(Pressable).props.onPress());
  expect(press).not.toHaveBeenCalled();
  act(() => tree.update(render(false, true)));
  expect(slot().props.style).toEqual(initial);
  expect(tree.root.findByType(Pressable).props.accessibilityLabel).toBe(label);
  expect(tree.root.findAllByType(ActivityIndicator)).toHaveLength(0);
});
it("invalidates label measurements when labels or typography size change", () => {
  const render = (size: "small" | "large", label: string) => <HjmNativeProvider><Button size={size} completion={{ confirmed: false, label }}>Save</Button></HjmNativeProvider>;
  act(() => { tree = create(render("small", "Saved")); });
  const slot = () => tree.root.findAllByType(View).find(node => node.props.style?.flexShrink === 1 && typeof node.props.style?.height === "number")!;
  expect(slot().props.style.height).toBe(36);
  act(() => tree.root.findAllByType(Text).find(node => node.props.onLayout)!.props.onLayout({ nativeEvent: { layout: { height: 72 } } }));
  expect(slot().props.style.height).toBe(72);
  act(() => tree.update(render("large", "Done")));
  expect(slot().props.style.height).toBe(48);
});
