import { access, mkdir, readFile, writeFile } from "node:fs/promises";

import { componentDefinitions } from "../dist/component-definitions.js";
import { designSystemVersion } from "../dist/version.js";
import { showcaseManifest } from "../dist/showcase.js";

const writeMode = process.argv.includes("--write");
const generatedDirectory = new URL("../docs/generated/", import.meta.url);
const docsDirectory = new URL("../docs/", import.meta.url);
const markdownUrl = new URL("component-maturity.md", generatedDirectory);
const jsonUrl = new URL("showcase-manifest.json", generatedDirectory);

const definitionByName = new Map(componentDefinitions.map((definition) => [definition.name, definition]));
const statusOrder = ["stable", "beta", "planned", "deprecated", "unsupported"];

function summarizeSurface(surface) {
  const counts = Object.fromEntries(statusOrder.map((status) => [status, 0]));
  for (const definition of componentDefinitions) counts[definition.surfaces[surface].status] += 1;
  return counts;
}

function formatSummary(counts) {
  return statusOrder
    .filter((status) => counts[status] > 0)
    .map((status) => `${status} ${counts[status]}`)
    .join(" · ");
}

function escapeCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

async function fileExists(url) {
  try {
    await access(url);
    return true;
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
}

const generatedComponents = await Promise.all(showcaseManifest.map(async (entry) => {
  const definition = definitionByName.get(entry.component.name);
  if (!definition) throw new Error(`Missing normalized component definition: ${entry.component.name}`);
  const authoredPath = `docs/${definition.id}.md`;
  const hasAuthoredDocumentation = await fileExists(new URL(`${definition.id}.md`, docsDirectory));
  return {
    id: definition.id,
    storyId: entry.storyId,
    name: definition.name,
    category: definition.category,
    platform: definition.surfaces.parity,
    contractStatus: definition.contract.status,
    surfaces: {
      web: definition.surfaces.web.status,
      native: definition.surfaces.native.status,
    },
    requirements: entry.requirements,
    documentation: {
      generated: "docs/generated/component-maturity.md",
      authored: hasAuthoredDocumentation ? authoredPath : null,
    },
  };
}));

const artifact = {
  schemaVersion: 2,
  designSystemVersion,
  packageName: "@hjm/design-contracts",
  components: generatedComponents,
};

const json = `${JSON.stringify(artifact, null, 2)}\n`;
const contractSummary = componentDefinitions.reduce(
  (counts, definition) => {
    counts[definition.contract.status] += 1;
    return counts;
  },
  { stable: 0, beta: 0, planned: 0, deprecated: 0 },
);
const webSummary = summarizeSurface("web");
const nativeSummary = summarizeSurface("native");
const markdownRows = generatedComponents.map((component) => {
  const evidence = component.requirements
    .map(({ surface, scenarios }) => `${surface}: ${scenarios.join(", ")}`)
    .join("; ");
  const authoredDoc = component.documentation.authored
    ? `[authored](../${component.id}.md)`
    : "generated only";
  return `| ${escapeCell(component.name)} | \`${component.storyId}\` | ${component.contractStatus} | ${component.surfaces.web} | ${component.surfaces.native} | ${authoredDoc} | ${escapeCell(evidence)} |`;
});
const markdown = `${[
  "# Component maturity and evidence manifest",
  "",
  `> Generated from \`@hjm/design-contracts\` ${designSystemVersion}. Do not edit this file directly; run \`pnpm contracts:sync\`.`,
  "",
  "This document is the human-readable projection of the same catalog and Showcase manifest consumed by product CI.",
  "",
  `- Contract: ${formatSummary(contractSummary)}`,
  `- Web renderer: ${formatSummary(webSummary)}`,
  `- Native renderer: ${formatSummary(nativeSummary)}`,
  "",
  "| Component | Canonical story ID | Contract | Web | Native | Documentation | Required evidence |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...markdownRows,
].join("\n")}\n`;

async function readExisting(url) {
  try {
    return await readFile(url, "utf8");
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return null;
    throw error;
  }
}

if (writeMode) {
  await mkdir(generatedDirectory, { recursive: true });
  await Promise.all([
    writeFile(markdownUrl, markdown, "utf8"),
    writeFile(jsonUrl, json, "utf8"),
  ]);
  console.log(`Synchronized ${generatedComponents.length} component contracts into docs/generated/.`);
} else {
  const [existingMarkdown, existingJson] = await Promise.all([
    readExisting(markdownUrl),
    readExisting(jsonUrl),
  ]);
  const stale = [];
  if (existingMarkdown !== markdown) stale.push("docs/generated/component-maturity.md");
  if (existingJson !== json) stale.push("docs/generated/showcase-manifest.json");
  if (stale.length > 0) {
    throw new Error(
      `Generated contract artifacts are missing or stale: ${stale.join(", ")}\nRun pnpm contracts:sync and commit the result.`,
    );
  }
  console.log(`Verified ${generatedComponents.length} synchronized component contracts.`);
}
